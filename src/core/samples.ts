// OWNER: core-data agent. Built-in ORIGINAL template designs (read-only; using one creates a copy).
//
// Each template is ASCII art (one char per cell) plus a char → colour map. The first map entry is the
// background. Palette ids are fixed ("<slug>-<n>") so templates are stable across reloads.
import { BASIC_COLORS } from './design';
import type { BasicColorName } from './design';
import { DEFAULT_PRINT } from './types';
import type { Design, Op, PrintSettings, PuzzleSettings } from './types';

interface TemplateSpec {
  slug: string;
  name: string;
  /** char → colour name; insertion order = palette order, first entry = background. */
  colors: Record<string, BasicColorName>;
  art: string[];
  puzzle: Omit<PuzzleSettings, 'legendMode'> & { legendMode?: PuzzleSettings['legendMode'] };
  print?: Partial<PrintSettings>;
}

function buildTemplate(spec: TemplateSpec): Design {
  const chars = Object.keys(spec.colors);
  const palette = chars.map((ch, i) => {
    const name = spec.colors[ch];
    return { id: `${spec.slug}-${i}`, name, hex: BASIC_COLORS[name] };
  });
  const idOf = new Map(chars.map((ch, i) => [ch, palette[i].id]));
  return {
    id: `tpl-${spec.slug}`,
    name: spec.name,
    width: spec.art[0].length,
    height: spec.art.length,
    palette,
    backgroundId: palette[0].id,
    cells: spec.art.flatMap((row) => Array.from(row, (ch) => idOf.get(ch) ?? palette[0].id)),
    puzzle: { legendMode: 'range', ...spec.puzzle },
    print: { ...DEFAULT_PRINT, ...spec.print },
    createdAt: 0,
    updatedAt: 0,
  };
}

